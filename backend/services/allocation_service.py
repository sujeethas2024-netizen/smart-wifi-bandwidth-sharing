# DISPLAY RESULTS
# ============================================================

def display_allocation_result(
    result
):
    """
    Display allocation results in the terminal.
    """

    print()

    print("=" * 70)

    print(
        "       SMART WI-FI BANDWIDTH SHARING"
    )

    print("=" * 70)

    print()

    print(
        f"Total Available Bandwidth : "
        f"{result['total_bandwidth']:.2f} Mbps"
    )

    print(
        f"Total Requested Bandwidth : "
        f"{result['total_requested_bandwidth']:.2f} Mbps"
    )

    print(
        f"Total Allocated Bandwidth : "
        f"{result['total_allocated_bandwidth']:.2f} Mbps"
    )

    print(
        f"Unused Bandwidth          : "
        f"{result['unused_bandwidth']:.2f} Mbps"
    )

    print()

    print("-" * 70)

    print(
        "USER BANDWIDTH ALLOCATION"
    )

    print("-" * 70)

    for user in result["users"]:

        print(

            f"User {user['user_id']:<3}"

            f"| Activity: "
            f"{user['activity']:<15}"

            f"| Requested: "
            f"{user['requested_bandwidth']:>7.2f} Mbps"

            f" | Allocated: "
            f"{user['allocated_bandwidth']:>7.2f} Mbps"

            f" | Utility: "
            f"{user['utility']:>7.4f}"

        )


    print()

    print("-" * 70)

    print(
        f"Bandwidth Utilization : "
        f"{result['utilization_percentage']:.2f}%"
    )

    print(
        f"Jain Fairness Index   : "
        f"{result['jain_fairness_index']:.4f}"
    )

    print(
        f"Fairness Status       : "
        f"{result['fairness_status']}"
    )

    print(
        f"Iterations             : "
        f"{result['iterations']}"
    )

    print("-" * 70)


