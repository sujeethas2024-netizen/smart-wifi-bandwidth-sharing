# ============================================================
# DETERMINE OVERALL WINNERS
# ============================================================

def determine_overall_winners(
    performance
):
    """
    Determine which strategy has the best
    average fairness, utilization and utility.
    """

    best_fairness = max(

        performance.items(),

        key=lambda item:
            item[1]["average_fairness"]

    )


    best_utilization = max(

        performance.items(),

        key=lambda item:
            item[1]["average_utilization"]

    )


    best_utility = max(

        performance.items(),

        key=lambda item:
            item[1]["average_utility"]

    )


    return {

        "fairness":
            best_fairness,

        "utilization":
            best_utilization,

        "utility":
            best_utility

    }


# ============================================================
# DISPLAY OVERALL WINNERS
# ============================================================

def display_overall_winners(
    winners
):
    """
    Display the overall winning strategies.
    """

    print()

    print("=" * 100)

    print(
        "             OVERALL WINNERS"
    )

    print("=" * 100)

    print()


    print(

        "Best Fairness     : "

        f"{winners['fairness'][0]} "

        f"({winners['fairness'][1]['average_fairness']:.4f})"

    )


    print(

        "Best Utilization  : "

        f"{winners['utilization'][0]} "

        f"({winners['utilization'][1]['average_utilization']:.2f}%)"

    )


    print(

        "Best Utility      : "

        f"{winners['utility'][0]} "

        f"({winners['utility'][1]['average_utility']:.4f})"

    )


    print()


# ============================================================
# MAIN ANALYSIS
# ============================================================

def run_analysis():
    """
    Run the complete results analysis.
    """

    print()

    print("=" * 100)

    print(
        "       SMART WI-FI BANDWIDTH RESULTS ANALYSIS"
    )

    print("=" * 100)


    # --------------------------------------------------------
    # Load CSV
    # --------------------------------------------------------

    results = load_results()


    print()

    print(
        f"Loaded {len(results)} experiment rows."
    )


    # --------------------------------------------------------
    # Analyze each user scenario
    # --------------------------------------------------------

    scenario_analysis = (

        analyze_user_scenarios(

            results

        )

    )


    display_scenario_analysis(

        scenario_analysis

    )


    # --------------------------------------------------------
    # Calculate overall performance
    # --------------------------------------------------------

    performance = (

        calculate_overall_performance(

            results

        )

    )


    display_overall_performance(

        performance

    )


    # --------------------------------------------------------
    # Determine winners
    # --------------------------------------------------------

    winners = (

        determine_overall_winners(

            performance

        )

    )


    display_overall_winners(

        winners

    )


    print()

    print("=" * 100)

    print(
        "             ANALYSIS COMPLETED"
    )

    print("=" * 100)

    print()


# ============================================================
# RUN DIRECTLY
# ============================================================

if __name__ == "__main__":

    run_analysis()