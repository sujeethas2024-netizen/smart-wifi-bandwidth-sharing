"""
Results Analysis

Reads the synthetic experimental dataset generated by
experiment_runner.py and compares:

1. Equal Allocation
2. Proportional Allocation
3. Game Theory Allocation

Metrics analysed:

- Bandwidth utilization
- Jain fairness index
- Average utility

No external APIs are used.
"""

import csv
import os


# ============================================================
# FILE CONFIGURATION
# ============================================================

INPUT_FILE = (
    "data/experiment_results.csv"
)


# ============================================================
# LOAD EXPERIMENT DATA
# ============================================================

def load_results(filename=INPUT_FILE):
    """
    Load experiment results from CSV.

    Returns
    -------
    list
        List of dictionaries containing experiment results.
    """

    if not os.path.exists(filename):

        raise FileNotFoundError(

            f"Could not find experiment data: "
            f"{filename}"

        )


    with open(
        filename,
        "r",
        encoding="utf-8"
    ) as file:

        reader = csv.DictReader(file)

        results = list(reader)


    # Convert numeric columns

    for row in results:

        row["number_of_users"] = int(
            row["number_of_users"]
        )

        row["total_bandwidth"] = float(
            row["total_bandwidth"]
        )

        row["total_allocated"] = float(
            row["total_allocated"]
        )

        row["utilization_percentage"] = float(
            row["utilization_percentage"]
        )

        row["jain_fairness_index"] = float(
            row["jain_fairness_index"]
        )

        row["average_utility"] = float(
            row["average_utility"]
        )


    return results


# ============================================================
# GROUP RESULTS BY NUMBER OF USERS
# ============================================================

def group_by_user_count(results):
    """
    Group experiment results according to
    the number of simulated users.
    """

    grouped = {}

    for row in results:

        number_of_users = row[
            "number_of_users"
        ]

        if number_of_users not in grouped:

            grouped[
                number_of_users
            ] = []

        grouped[
            number_of_users
        ].append(row)


    return grouped


# ============================================================
# FIND BEST STRATEGY
# ============================================================

def find_best_strategy(
    rows,
    metric,
    higher_is_better=True
):
    """
    Find the strategy with the best value
    for a given metric.
    """

    if not rows:

        return None


    if higher_is_better:

        best = max(
            rows,
            key=lambda row: row[metric]
        )

    else:

        best = min(
            rows,
            key=lambda row: row[metric]
        )


    return best


# ============================================================
# ANALYZE EACH USER SCENARIO
# ============================================================

def analyze_user_scenarios(results):
    """
    Analyze which strategy performs best for
    every user-count scenario.
    """

    grouped = group_by_user_count(
        results
    )

    analysis = []


    for number_of_users in sorted(
        grouped.keys()
    ):

        rows = grouped[
            number_of_users
        ]


        # --------------------------------------------
        # Best fairness
        # --------------------------------------------

        best_fairness = find_best_strategy(

            rows,

            "jain_fairness_index",

            higher_is_better=True

        )


        # --------------------------------------------
        # Best utilization
        # --------------------------------------------

        best_utilization = find_best_strategy(

            rows,

            "utilization_percentage",

            higher_is_better=True

        )


        # --------------------------------------------
        # Best utility
        # --------------------------------------------

        best_utility = find_best_strategy(

            rows,

            "average_utility",

            higher_is_better=True

        )


        analysis.append({

            "number_of_users":
                number_of_users,

            "best_fairness_strategy":
                best_fairness["strategy"],

            "best_fairness_value":
                best_fairness[
                    "jain_fairness_index"
                ],

            "best_utilization_strategy":
                best_utilization["strategy"],

            "best_utilization_value":
                best_utilization[
                    "utilization_percentage"
                ],

            "best_utility_strategy":
                best_utility["strategy"],

            "best_utility_value":
                best_utility[
                    "average_utility"
                ]

        })


    return analysis


# ============================================================
# CALCULATE OVERALL PERFORMANCE
# ============================================================

def calculate_overall_performance(results):
    """
    Calculate average performance of each strategy
    across all experiments.
    """

    strategies = {}


    # --------------------------------------------------------
    # Group by strategy
    # --------------------------------------------------------

    for row in results:

        strategy = row[
            "strategy"
        ]

        if strategy not in strategies:

            strategies[
                strategy
            ] = []

        strategies[
            strategy
        ].append(row)


    # --------------------------------------------------------
    # Calculate averages
    # --------------------------------------------------------

    performance = {}


    for strategy, rows in strategies.items():

        count = len(rows)


        average_fairness = (

            sum(
                row[
                    "jain_fairness_index"
                ]

                for row in rows

            )

            / count

        )


        average_utilization = (

            sum(
                row[
                    "utilization_percentage"
                ]

                for row in rows

            )

            / count

        )


        average_utility = (

            sum(
                row[
                    "average_utility"
                ]

                for row in rows

            )

            / count

        )


        performance[
            strategy
        ] = {

            "average_fairness":
                average_fairness,

            "average_utilization":
                average_utilization,

            "average_utility":
                average_utility

        }


    return performance


# ============================================================
# PRINT DETAILED RESULTS
# ============================================================

def display_scenario_analysis(
    analysis
):
    """
    Display the best strategy for each
    user-count scenario.
    """

    print()

    print("=" * 100)

    print(
        "             PERFORMANCE BY USER COUNT"
    )

    print("=" * 100)

    print()


    print(

        f"{'Users':<10}"

        f"{'Best Fairness':<28}"

        f"{'Best Utilization':<28}"

        f"{'Best Utility':<28}"

    )


    print("-" * 100)


    for row in analysis:

        print(

            f"{row['number_of_users']:<10}"

            f"{row['best_fairness_strategy']:<20}"

            f"{row['best_fairness_value']:>7.4f}    "

            f"{row['best_utilization_strategy']:<20}"

            f"{row['best_utilization_value']:>7.2f}%    "

            f"{row['best_utility_strategy']:<20}"

            f"{row['best_utility_value']:>7.4f}"

        )


    print("-" * 100)


# ============================================================
# PRINT OVERALL RESULTS
